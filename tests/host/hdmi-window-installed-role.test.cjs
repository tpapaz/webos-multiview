const assert = require('node:assert/strict');
const {id, version} = require('../../scripts/hdmi-window-report.cjs');
const {validateGeneratedRole, validateGeneratedManifest} = require('../../scripts/hdmi-window-installed-role.cjs');
const manifest = {id, version, roleFilesPrv: ['/var/palm/ls2-dev/roles/prv/' + id + '.json'],
    roleFilesPub: ['/var/palm/ls2-dev/roles/pub/' + id + '.json'],
    clientPermissionFiles: ['/var/luna-service2-dev/client-permissions.d/' + id + '.app.json']};
validateGeneratedManifest(manifest);
assert.throws(() => validateGeneratedManifest({...manifest, version: '0.1.3'}));
assert.throws(() => validateGeneratedManifest({...manifest, apiPermissionFiles: ['/tmp/extra.json']}));
// Sanitized C1 public-role fixture: generated by the TV, never deployed by us.
const pub = {role: {
    exeName: '/media/developer/apps/usr/palm/applications/' + id + '/multiview-hdmi-window',
    type: 'regular', allowedNames: ['com.webos.media.client.*', 'com.webos.rm.client.*',
        'com.webos.pipeline.*', 'com.webos.pipe.avmuteclient.*', 'com.webos.vt.*',
        'com.webos.chromium.media.*', id, '']},
permissions: [
    {service: 'com.webos.media.client.*', outbound: ['com.webos.media'], inbound: ['com.webos.media']},
    {service: 'com.webos.rm.client.*', outbound: ['com.webos.media'], inbound: ['com.webos.media']},
    {service: 'com.webos.pipeline.*', outbound: ['com.webos.pipelinectrl.*'], inbound: ['com.webos.pipelinectrl.*']},
    {service: 'com.webos.pipe.avmuteclient.*', outbound: ['com.webos.service.avmutemanager'], inbound: []},
    {service: 'com.webos.vt.*', outbound: ['*'], inbound: ['*']},
    {service: 'com.webos.chromium.media.*', outbound: ['*'], inbound: []},
    {service: id, outbound: ['*'], inbound: []}
]};
const copy = value => JSON.parse(JSON.stringify(value));
const prv = copy(pub);
prv.role.allowedNames[3] = 'com.webos.avconnector.*';
prv.permissions[3] = {service: 'com.webos.avconnector.*',
    outbound: ['com.webos.service.videooutput', 'com.webos.service.audio', 'com.webos.service.utp.extinputs'], inbound: []};
for (const [side, original] of [['pub', pub], ['prv', prv]]) {
    validateGeneratedRole(original, side);
    for (const mutate of [
        r => {r.role.exeName += '-other';},
        r => {r.role.type = 'privileged';},
        r => {r.role.allowedNames.push('*');},
        r => {r.permissions[6].service = 'other';},
        r => {r.permissions[6].inbound.push('*');},
        r => {r.permissions.push(copy(r.permissions[6]));},
        r => {r.permissions[3].outbound.push('*');},
        r => {r.role.allowedNames.splice(6, 1);}
    ]) {
        const changed = copy(original);
        mutate(changed);
        assert.throws(() => validateGeneratedRole(changed, side));
    }
}
assert.throws(() => validateGeneratedRole(pub, 'prv'));
assert.throws(() => validateGeneratedRole(prv, 'pub'));
assert.throws(() => validateGeneratedRole(pub, 'other'));
console.log('C1 generated-role template, own identity and permission-boundary checks passed');
